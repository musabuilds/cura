"""data/STATS.md — the dataset's coverage, regenerated on every merge so no document quotes stale numbers."""

from __future__ import annotations

from collections import Counter

from cura.pipeline.merge import load_canonical
from cura.reference import read_csv


def _table(title: str, counter: Counter | dict, labels: dict[str, str] | None = None) -> str:
    rows = "\n".join(f"| {labels.get(k, k) if labels else k} | {v:,} |" for k, v in counter.items())
    return f"| {title} | count |\n|---|---:|\n{rows}\n"


def _pct(n: int, total: int) -> str:
    return f"{n:,} ({n / total:.0%})" if total else "0"


def markdown(report: dict) -> str:
    facilities = [f for f in load_canonical("facilities") if f["status"] != "merged"]
    practitioners = load_canonical("practitioners")
    roles = load_canonical("roles")
    n = len(facilities)
    types = {r["code"]: r["name_en"] for r in read_csv("facility_types.csv")}
    govs = {r["iso_3166_2"]: r["name_en"] for r in read_csv("governorates.csv")}
    own = {r["code"]: r["name_en"] for r in read_csv("ownership.csv")}

    coverage = {
        "coordinates": sum(1 for f in facilities if f.get("location")),
        "surveyed coordinates (exact)": sum(
            1 for f in facilities if (f.get("location") or {}).get("precision") == "exact"
        ),
        "governorate": sum(1 for f in facilities if f["address"].get("governorate")),
        "phone": sum(1 for f in facilities if f["contact"].get("phones")),
        "website": sum(1 for f in facilities if f["contact"].get("website")),
        "opening hours": sum(1 for f in facilities if f["hours"].get("opening_hours") or f["hours"].get("text")),
        "ownership known": sum(1 for f in facilities if f["ownership"] != "unknown"),
        "insurance accepted": sum(1 for f in facilities if f.get("insurance")),
        "Arabic name": sum(1 for f in facilities if f["name"].get("ar")),
        "English name": sum(1 for f in facilities if f["name"].get("en")),
        "2+ independent sources": sum(1 for f in facilities if len({s["source"] for s in f["sources"]}) > 1),
    }
    with_role = len({r["practitioner_id"] for r in roles})
    multi = Counter(r["practitioner_id"] for r in roles)
    sources = report.get("sources", {})

    parts = [
        "# Dataset statistics",
        "",
        f"Generated by `cura merge` at {report.get('built_at')}. Do not edit by hand.",
        "",
        f"**{n:,} facilities · {len(practitioners):,} practitioners · {len(roles):,} practitioner–facility roles · "
        f"{report.get('insurers', 0)} insurers · {report.get('prices', 0)} price references · "
        f"{sum(1 for m in sources.values() if not m.get('disabled'))} sources**",
        "",
        "## Facilities by type",
        "",
        _table("type", dict(Counter(f["type"] for f in facilities).most_common()), types),
        "## Facilities by governorate",
        "",
        _table(
            "governorate",
            dict(Counter(f["address"].get("governorate") or "unknown" for f in facilities).most_common()),
            govs,
        ),
        "## Facilities by ownership",
        "",
        _table("ownership", dict(Counter(f["ownership"] for f in facilities).most_common()), own),
        "## Field coverage (facilities)",
        "",
        "| field | known |\n|---|---:|\n" + "\n".join(f"| {k} | {_pct(v, n)} |" for k, v in coverage.items()) + "\n",
        "## Practitioners",
        "",
        "| measure | count |\n|---|---:|\n"
        f"| practitioners | {len(practitioners):,} |\n"
        f"| linked to at least one facility | {_pct(with_role, len(practitioners))} |\n"
        f"| working at 2+ facilities | {sum(1 for v in multi.values() if v > 1):,} |\n"
        f"| specialty known | {_pct(sum(1 for p in practitioners if p.get('specialty')), len(practitioners))} |\n"
        f"| licence verified by Cura | {sum(1 for p in practitioners if p.get('license_verified')):,} |\n",
        "## Sources",
        "",
        "| source | records | license | retrieved |\n|---|---:|---|---|\n"
        + "\n".join(
            f"| `{s}` | {m.get('record_count') or 0:,} | {m.get('license') or 'unknown'} "
            f"| {(m.get('retrieved_at') or '')[:10]} |"
            for s, m in sources.items()
            if not m.get("disabled")
        )
        + "\n",
    ]
    return "\n".join(parts)
